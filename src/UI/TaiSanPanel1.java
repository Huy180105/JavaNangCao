      private void displaySelectedRow() {
    int selectedRow = table.getSelectedRow();
    if (selectedRow == -1) return;

    Object v0 = table.getValueAt(selectedRow, 0);
    Object v1 = table.getValueAt(selectedRow, 1);
    Object v2 = table.getValueAt(selectedRow, 2);
    Object v3 = table.getValueAt(selectedRow, 3);
    Object v4 = table.getValueAt(selectedRow, 4);

    selectedMats = (v0 != null) ? Integer.parseInt(v0.toString()) : -1;
    txtTenTaiSan.setText(v1 != null ? v1.toString() : "");
    txtSoLuong.setText(v2 != null ? v2.toString() : "");

    if (v3 != null) {
        cboTinhTrang.setSelectedItem(v3.toString());
    } else {
        cboTinhTrang.setSelectedIndex(0);
    }

    txtMaPhong.setText(v4 != null ? v4.toString() : "");


        // TODO add your handling code here:
    }//GEN-LAST:event_tableMouseClicked

