    @Override
   public void hienThiDanhSach(List<TaiSan> list) {
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0);

        for (TaiSan ts : list) {
            model.addRow(new Object[]{
               ts.getMats(),
                ts.getTents(),
                ts.getSoluong(),
                ts.getTinhtrang(),
                ts.getMaphong()
            });
        }
    }
    

