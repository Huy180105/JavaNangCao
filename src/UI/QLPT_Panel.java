    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
PhuongTien pt = getFormInfo();
        
        if (pt.getCccd().isEmpty() || pt.getBienSo().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập CCCD chủ xe và Biển số!");
            return;
        }
        
        
        controller.themPhuongTien(pt, pt.getCccd());
        
        
        loadDataToTable();
        resetForm();// TODO add your handling code here:
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        int index = jTable1.getSelectedRow();
        if (index < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn xe cần sửa trong bảng!");
            return;
        }
        
        
        int maPT = Integer.parseInt(jTable1.getValueAt(index, 0).toString());
        
        PhuongTien pt = getFormInfo();
        pt.setMaPT(maPT);
        
        
        controller.capNhatPhuongTien(pt);
        
        
        loadDataToTable();
        resetForm();
    }//GEN-LAST:event_btnSuaActionPerformed
    
    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        int index = jTable1.getSelectedRow();
        if (index >= 0) {
            int maPT = Integer.parseInt(jTable1.getValueAt(index, 0).toString());
            
           
            controller.xoaPhuongTien(maPT);
            
            
            loadDataToTable();
            resetForm();
        } else {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn dòng để xóa!");
        }
    }//GEN-LAST:event_btnXoaActionPerformed

    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed
        // TODO add your handling code here:
        String keyword = txtTimKiem.getText().trim();
        
        
        List<PhuongTien> list;
        if (keyword.isEmpty()) {
            list = controller.getDanhSachPhuongTien();
        } else {
            list = controller.timKiemPhuongTien(keyword);
        }
        
        
        tableModel.setRowCount(0);
        for (PhuongTien pt : list) {
            addObjToRow(pt);
        }
        
    }//GEN-LAST:event_btnTimKiemActionPerformed
