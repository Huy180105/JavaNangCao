    private void initTable() {
        
        tableModel = new DefaultTableModel();
        
        String[] columns = {"Mã PT", "Tên chủ xe", "CCCD", "SĐT", "Ngày sinh", "Loại xe", "Hiệu xe", "Biển số", "Màu xe", "Ngày ĐK"};
        tableModel.setColumnIdentifiers(columns);
        
        jTable1.setModel(tableModel);
    }

    
    private void loadDataToTable() {
        
        tableModel.setRowCount(0); 
        
        
        List<PhuongTien> list = controller.getDanhSachPhuongTien();
        
        
        for (PhuongTien pt : list) {
            addObjToRow(pt);
        }
    }
    
    
    private void addObjToRow(PhuongTien pt) {
        tableModel.addRow(new Object[]{
            pt.getMaPT(),
            pt.getTenChuSoHuu(),
            pt.getCccd(),
            pt.getSdt(),
            pt.getNgaySinhChu(),
            pt.getLoaiXe(),
            pt.getHieuXe(),
            pt.getBienSo(),
            pt.getMauXe(),
            pt.getNgayDangKy()
        });
    }

    
    private PhuongTien getFormInfo() {
        PhuongTien pt = new PhuongTien();
        pt.setLoaiXe(txtLoaiXe.getText());
        pt.setHieuXe(txtHieuXe.getText());
        pt.setBienSo(txtBienSo.getText());
        pt.setMauXe(txtMauXe.getText());
        pt.setCccd(txtCCCD.getText()); 
        
        
        if (dateNgayDangKy.getDate() != null) {
            pt.setNgayDangKy(dateNgayDangKy.getDate());
        } else {
            pt.setNgayDangKy(new java.util.Date());
        }
        return pt;
    }

    
    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {                                     
        int index = jTable1.getSelectedRow(); // Lấy vị trí dòng đang chọn
        
        
        if (index >= 0) {
            txtTenChu.setText(getValue(index, 1));
            txtCCCD.setText(getValue(index, 2));
            txtSDT.setText(getValue(index, 3));
            
            
            Object dob = jTable1.getValueAt(index, 4);
            if(dob != null && dob instanceof java.util.Date) {
                 dateNgaySinh.setDate((java.util.Date) dob);
            }

            txtLoaiXe.setText(getValue(index, 5));
            txtHieuXe.setText(getValue(index, 6));
            txtBienSo.setText(getValue(index, 7));
            txtMauXe.setText(getValue(index, 8));
            
            
            Object regDate = jTable1.getValueAt(index, 9);
            if(regDate != null && regDate instanceof java.util.Date) {
                 dateNgayDangKy.setDate((java.util.Date) regDate);
            }
        }
    }
    
    
    private String getValue(int row, int col) {
        return jTable1.getValueAt(row, col).toString();
    }
    
                                          


    
    
